$script:RA_UiLang = 'es'

function Resolve-UiLanguage {
    # 'auto' sigue el idioma de Windows: espanol si es espanol, ingles si no.
    param([string]$Setting = 'auto', [string]$UiCulture = '')

    switch ($Setting.Trim().ToLowerInvariant()) {
        'es' { return 'es' }
        'en' { return 'en' }
        default {
            if ($UiCulture -eq '') { $UiCulture = [Globalization.CultureInfo]::CurrentUICulture.TwoLetterISOLanguageName }
            if ($UiCulture -eq 'es') { return 'es' }
            return 'en'
        }
    }
}

function Set-UiLanguage {
    param([string]$Lang)
    $script:RA_UiLang = $(if ($Lang -eq 'en') { 'en' } else { 'es' })
}

function Get-UiLanguage {
    return $script:RA_UiLang
}

function Get-EnglishTable {
    return $script:RA_En
}

function T {
    # El texto en el idioma de la interfaz; el espanol original si no hay traduccion.
    param([string]$Es)

    if ($script:RA_UiLang -eq 'en' -and $script:RA_En.ContainsKey($Es)) { return $script:RA_En[$Es] }
    return $Es
}

function Convert-XamlLanguage {
    # Traduce los textos de un XAML (Text, Content, ToolTip, Header, Title). En
    # espanol lo devuelve igual.
    param([string]$Xaml)

    if ($script:RA_UiLang -ne 'en') { return $Xaml }

    return [regex]::Replace($Xaml, '\b(Text|Content|ToolTip|Header|Title|AutomationProperties\.Name)="([^"{][^"]*)"', [Text.RegularExpressions.MatchEvaluator]{
        param($m)
        $value = $m.Groups[2].Value
        if ($script:RA_En.ContainsKey($value)) { return $m.Groups[1].Value + '="' + $script:RA_En[$value] + '"' }
        return $m.Value
    })
}

function Add-AutomationNames {
    # Los lectores de pantalla leen AutomationProperties.Name: los controles que
    # solo tienen un ToolTip (los botones con un icono) lo reciben como nombre.
    param([string]$Xaml)

    return [regex]::Replace($Xaml, '<(Button|Slider|RadioButton|TextBox|ListBox)\b([^>]*?)\bToolTip="([^"{][^"]*)"([^>]*)>', [Text.RegularExpressions.MatchEvaluator]{
        param($m)
        $tag = $m.Value
        if ($tag -match 'AutomationProperties\.Name=') { return $tag }
        return '<' + $m.Groups[1].Value + $m.Groups[2].Value + 'ToolTip="' + $m.Groups[3].Value + '" AutomationProperties.Name="' + $m.Groups[3].Value + '"' + $m.Groups[4].Value + '>'
    })
}
